"""User-local, reversible XP tray/clock presentation over KDE's own widgets.

Keep the native system-tray plugin ID, model, configuration and icon actions.
Only the QML presentation is patched; expansion reveals explicitly hidden icons
without changing saved visibility settings or showing inactive automatic icons.
"""
import json
import os
from pathlib import Path
import shutil

import hostexec as host
import paths

ROOT = Path(paths.REAL_HOME) / ".local/share/plasma/plasmoids"
MARKER = "X-Xp2plasma-Panel-Override"
IDS = ("org.kde.plasma.systemtray", "org.kde.plasma.digitalclock")


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise RuntimeError(f"Unexpected Plasma widget layout: {old[:70]}")
    return text.replace(old, new, 1)


def backdrop(prefix):
    return '''
    KSvg.FrameSvg {
        id: xpTraySvg
        imagePath: "widgets/xp-tray"
    }
    readonly property bool xpTrayAvailable: xpTraySvg.hasElementPrefix("tray")
    KSvg.FrameSvgItem {
        id: xpTrayBackground
        visible: root.xpTrayAvailable && Plasmoid.formFactor === PlasmaCore.Types.Horizontal
        z: -1
        anchors.fill: parent
        anchors.topMargin: -3
        anchors.bottomMargin: -3
        anchors.leftMargin: %s
        anchors.rightMargin: -8
        imagePath: "widgets/xp-tray"
        prefix: "%s"
    }
''' % ("0" if prefix == "tray" else "-8", prefix)


EXPANDER = '''// Generated by XPLasma; original widget remains the fallback.
import QtQuick
import org.kde.ksvg as KSvg
import org.kde.kirigami as Kirigami
import org.kde.plasma.core as PlasmaCore
import org.kde.plasma.plasmoid

Loader {
    id: expanderLoader
    property int iconSize: Kirigami.Units.iconSizes.small
    sourceComponent: root.xpTrayAvailable && !root.vertical ? xpArrow : stockArrow
    Component {
        id: stockArrow
        PlasmaExpanderArrow { iconSize: expanderLoader.iconSize }
    }
    Component {
        id: xpArrow
        PlasmaCore.ToolTipArea {
            id: arrow
            implicitWidth: 20
            implicitHeight: 20
            activeFocusOnTab: true
            subText: root.xpTrayExpanded ? i18n("Hide inactive icons") : i18n("Show hidden icons")
            Accessible.name: subText
            Accessible.role: Accessible.Button
            function toggleIcons() {
                root.xpTrayExpanded = !root.xpTrayExpanded;
            }
            Accessible.onPressAction: toggleIcons()
            Keys.onPressed: event => {
                if (event.key === Qt.Key_Space || event.key === Qt.Key_Return || event.key === Qt.Key_Enter) {
                    toggleIcons();
                    event.accepted = true;
                }
            }
            KSvg.SvgItem {
                anchors.centerIn: parent
                width: 20
                height: 20
                svg: KSvg.Svg { imagePath: "widgets/xp-tray" }
                elementId: (root.xpTrayExpanded ? "collapse-" : "expand-")
                    + (mouse.pressed ? "pressed" : mouse.containsMouse ? "hover" : "normal")
            }
            MouseArea {
                id: mouse
                anchors.fill: parent
                hoverEnabled: true
                onClicked: arrow.toggleIcons()
            }
        }
    }
}
'''


TRAY_STATE = '''
    property bool xpTrayExpanded: false
    readonly property var xpHiddenItems: Plasmoid.configuration.hiddenItems
    function xpExplicitlyHidden(itemId) {
        return root.xpTrayAvailable && !root.vertical && xpHiddenItems.indexOf(itemId) !== -1;
    }
    function xpRevealHidden(itemId) {
        return root.xpTrayExpanded && xpExplicitlyHidden(itemId);
    }
    function xpRefreshFilters() {
        if (activeModel) activeModel.invalidateFilter();
        if (hiddenModel) hiddenModel.invalidateFilter();
        if (xpExpandableModel) xpExpandableModel.invalidateFilter();
    }
    onXpTrayExpandedChanged: xpRefreshFilters()
    onXpHiddenItemsChanged: xpRefreshFilters()

    KItemModels.KSortFilterProxyModel {
        id: xpExpandableModel
        filterRoleName: "effectiveStatus"
        filterRowCallback: (sourceRow, sourceParent) => {
            const index = sourceModel.index(sourceRow, 0, sourceParent);
            // ItemId is the same base role used by KDE's ConfigEntries.qml.
            return sourceModel.data(index, filterRole) === PlasmaCore.Types.PassiveStatus
                && root.xpExplicitlyHidden(sourceModel.data(index, Qt.UserRole + 2));
        }
        Component.onCompleted: sourceModel = Plasmoid.systemTrayModel
    }
'''


def patch_main(source, tray):
    if "import org.kde.ksvg as KSvg" not in source:
        source = replace_once(source, "import QtQuick\n", "import QtQuick\nimport org.kde.ksvg as KSvg\n")
    source = replace_once(source, "    id: root\n", "    id: root\n" + backdrop("tray" if tray else "clock"))
    if tray:
        source = replace_once(source, "    readonly property bool vertical:",
            TRAY_STATE + "\n    readonly property bool vertical:")
        # Revealed icons retain PassiveStatus (1) in the native model; normal
        # panel icons have ActiveStatus (2). A stable ascending sort groups the
        # revealed icons on the left, preserving source order within each group.
        # Since the tray is right-anchored, normal icons keep their screen x.
        source = replace_once(source, "        id: activeModel\n",
            "        id: activeModel\n"
            "        sortRoleName: \"effectiveStatus\"\n"
            "        sortOrder: Qt.AscendingOrder\n"
            "        sortColumn: root.xpTrayAvailable && !root.vertical ? 0 : -1\n")
        source = replace_once(source, "return value === PlasmaCore.Types.ActiveStatus;",
            "return value === PlasmaCore.Types.ActiveStatus\n"
            "                || (value === PlasmaCore.Types.PassiveStatus\n"
            "                    && root.xpRevealHidden(sourceModel.data(sourceModel.index(sourceRow, 0, sourceParent), Qt.UserRole + 2)));")
        source = replace_once(source, "return value === PlasmaCore.Types.PassiveStatus\n",
            "return value === PlasmaCore.Types.PassiveStatus\n"
            "                && !root.xpRevealHidden(sourceModel.data(sourceModel.index(sourceRow, 0, sourceParent), Qt.UserRole + 2));\n")
        source = replace_once(source, "                id: tasksGrid\n",
            "                id: tasksGrid\n                Layout.row: 0\n                Layout.column: !root.vertical && root.xpTrayAvailable ? 1 : 0\n"
            "                // With no expander, reserve the theme's left cap ourselves.\n"
            "                Layout.leftMargin: root.xpTrayAvailable && !root.vertical && !expander.visible\n"
            "                    ? xpTrayBackground.margins.left : 0\n")
        source = replace_once(source, "                id: expander\n",
            "                id: expander\n                Layout.row: root.vertical ? 1 : 0\n                Layout.column: root.vertical || root.xpTrayAvailable ? 0 : 1\n")
        source = replace_once(source, "visible: root.hiddenLayout.itemCount > 0",
            "visible: root.xpTrayAvailable && !root.vertical\n"
            "                    ? root.xpTrayExpanded || xpExpandableModel.count > 0\n"
            "                    : root.hiddenLayout.itemCount > 0")
        source = replace_once(source, "readonly property int smallIconSize: Kirigami.Units.iconSizes.smallMedium",
            "readonly property int smallIconSize: root.xpTrayAvailable ? 16 : Kirigami.Units.iconSizes.smallMedium")
        source = replace_once(source, "readonly property int cellSpacing: Kirigami.Units.smallSpacing",
            "readonly property int cellSpacing: root.xpTrayAvailable ? 2 : Kirigami.Units.smallSpacing")
    return source


TRAY_ICON_SHADOW = '''
            // Presentation only: preserve the native icon pixels and hit area.
            layer.enabled: root.xpTrayAvailable && !root.vertical && abstractItem.inVisibleLayout
                && GraphicsInfo.api !== GraphicsInfo.Software
            layer.smooth: false
            layer.effect: MultiEffect {
                shadowEnabled: true
                shadowColor: "#000000"
                shadowOpacity: 0.35
                shadowBlur: 0.15
                blurMax: 4
                shadowHorizontalOffset: 0
                shadowVerticalOffset: 1
                autoPaddingEnabled: true
            }
'''


def patch_tray_item(source):
    source = replace_once(source, "import QtQuick\n", "import QtQuick\nimport QtQuick.Effects\n")
    source = replace_once(source, "            id: iconContainer\n",
                          "            id: iconContainer\n" + TRAY_ICON_SHADOW)
    # Promoted passive items must behave like panel icons, not popup rows
    # (no text labels, popup hit areas, or differently parented applets).
    return replace_once(source,
        "effectiveStatus: model.effectiveStatus || PlasmaCore.Types.UnknownStatus",
        "effectiveStatus: model.effectiveStatus === PlasmaCore.Types.PassiveStatus && root.xpRevealHidden(itemId)\n"
        "        ? PlasmaCore.Types.ActiveStatus : (model.effectiveStatus || PlasmaCore.Types.UnknownStatus)")


def owned(path):
    try:
        return json.loads((path / "metadata.json").read_text()).get(MARKER) is True
    except (OSError, ValueError):
        return False


def patch_clock(source):
    # KDE converts points through the monitor's *physical* pixel density.
    # On a small high-density screen that inflates 8pt even at 100% scale.
    # XP's sizes are 96-DPI logical pixels; Qt handles output scaling itself.
    return replace_once(source,
        "const pixelsPerInch = Screen.pixelDensity * 25.4",
        "const pixelsPerInch = root.xpTrayAvailable ? 96 : Screen.pixelDensity * 25.4")


def install():
    prepared = []
    # Check both widgets before replacing either installed override.
    for plugin in IDS:
        dest = ROOT / plugin
        if dest.exists() and not owned(dest):
            raise RuntimeError(f"Refusing to replace your existing widget override: {dest}")
        system = f"/usr/share/plasma/plasmoids/{plugin}"
        source = host.read_text(f"{system}/contents/ui/main.qml")
        meta = json.loads(host.read_text(f"{system}/metadata.json") or "{}")
        if not source or not meta:
            raise RuntimeError(f"Cannot read the installed Plasma widget: {plugin}")
        tray = plugin == IDS[0]
        patched = patch_main(source, tray)
        clock = None if tray else patch_clock(host.read_text(f"{system}/contents/ui/DigitalClock.qml"))
        item = patch_tray_item(host.read_text(f"{system}/contents/ui/items/AbstractItem.qml")) if tray else None
        prepared.append((plugin, system, meta, patched, clock, item))

    for plugin, system, meta, patched, clock, item in prepared:
        dest = ROOT / plugin
        staging = ROOT / (plugin + ".xplasma-new")
        if staging.exists():
            if not owned(staging):
                raise RuntimeError(f"Unrecognised staging directory: {staging}")
            shutil.rmtree(staging)
        staging.mkdir(parents=True)
        meta[MARKER] = True
        (staging / "metadata.json").write_text(json.dumps(meta, indent=2))
        host.copy_tree(f"{system}/contents", str(staging / "contents"))
        ui = staging / "contents/ui"
        (ui / "main.qml").write_text(patched)
        if plugin == IDS[0]:
            (ui / "ExpanderArrow.qml").rename(ui / "PlasmaExpanderArrow.qml")
            (ui / "ExpanderArrow.qml").write_text(EXPANDER)
            (ui / "items/AbstractItem.qml").write_text(item)
        else:
            (ui / "DigitalClock.qml").write_text(clock)
        if dest.exists():
            shutil.rmtree(dest)  # only our marked generated copy; KDE's original is untouched
        os.rename(staging, dest)


def remove():
    for plugin in IDS:
        for path in (ROOT / plugin, ROOT / (plugin + ".xplasma-new"), ROOT / (plugin + ".xp2plasma-new")):
            if owned(path):
                shutil.rmtree(path)
