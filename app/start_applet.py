"""A fork of Plasma's Kickoff launcher (org.kde.plasma.kickoff) whose panel
button is the theme's XP Start pill with real normal / hot / pressed states.

Kickoff's file-image button has no hover or pressed feedback and sits inside
the panel's content margins, so the package is copied from the system
Kickoff at install time (it always matches the running Plasma) and its
compact representation is patched to:
  * swap the image between <icon>-normal.png / -hover.png / -pressed.png
  * overhang the panel's top/bottom margins so the pill is bar-height and
    flush with the left edge, like XP.
The themed menu uses KDE's native models; classic/missing StartPanel artwork
retains stock Kickoff. Favorites and Meta-key activation keep the same identity.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
from pathlib import Path

import hostexec as host
import paths

APPLET_ID = "fyi.hotsocket.xplasma.start"
LEGACY_APPLET_ID = "org.xp2plasma.start"   # xp2plasma's; the layout replaces it
SYSTEM_KICKOFF = "/usr/share/plasma/plasmoids/org.kde.plasma.kickoff"
USER_PLASMOIDS = os.path.expanduser("~/.local/share/plasma/plasmoids")

_SOURCE_LINE = 'source: Plasmoid.icon.startsWith("file:/") ? Plasmoid.icon : ""'
_SOURCE_PATCH = (
    'source: Plasmoid.icon.startsWith("file:/") ? '
    '(kickoff.expanded || compactRoot.pressed ? Plasmoid.icon.replace("-normal.png", "-pressed.png") : '
    '(compactRoot.containsMouse ? Plasmoid.icon.replace("-normal.png", "-hover.png") : Plasmoid.icon)) : ""'
)
_ROW_ANCHOR = "            id: iconLabelRow\n            anchors.fill: parent\n"


def _tree_hash(path: str) -> str:
    h = hashlib.sha1()
    for root, _dirs, files in os.walk(path):
        for fn in sorted(files):
            p = os.path.join(root, fn)
            h.update(os.path.relpath(p, path).encode())
            with open(p, "rb") as f:
                h.update(f.read())
    return h.hexdigest()


def install_start_applet(overhang_vertical: int, overhang_left: int, theme=None) -> bool:
    """Build/refresh the forked applet package. Returns True if it changed
    on disk (plasmashell must be restarted before it can be added)."""
    dest = os.path.join(USER_PLASMOIDS, APPLET_ID)
    before = _tree_hash(dest) if os.path.isdir(dest) else None
    staging = dest + ".new"
    if os.path.isdir(staging):
        shutil.rmtree(staging)
    # The system Kickoff is a system path, not something this app ships, so it
    # is read through hostexec along with everything else that belongs to the
    # machine rather than to us.
    host.copy_tree(os.path.join(SYSTEM_KICKOFF, "contents"), os.path.join(staging, "contents"))

    meta = json.loads(host.read_text(os.path.join(SYSTEM_KICKOFF, "metadata.json")) or "{}")
    if not meta:
        shutil.rmtree(staging, ignore_errors=True)
        raise RuntimeError(
            f"couldn't read {SYSTEM_KICKOFF}/metadata.json -- is Plasma's Kickoff applet installed?")
    plugin = meta["KPlugin"]
    meta["KPlugin"] = {
        "Id": APPLET_ID,
        "Name": "XP Start Button",
        "Description": "Application Launcher (Kickoff) with a Windows XP Start button, generated by XPLasma",
        "Authors": plugin.get("Authors", []),
        "Category": plugin.get("Category", "Application Launchers"),
        "Icon": plugin.get("Icon", "start-here-kde"),
        "License": plugin.get("License", "GPL-2.0+"),
        "Version": plugin.get("Version", "1.0"),
    }
    with open(os.path.join(staging, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

    main_qml = os.path.join(staging, "contents", "ui", "main.qml")
    with open(main_qml, encoding="utf-8") as f:
        qml = f.read()
    if _SOURCE_LINE not in qml or _ROW_ANCHOR not in qml:
        shutil.rmtree(staging)
        raise RuntimeError("this Plasma's Kickoff main.qml doesn't match the expected layout; not patching")
    qml = qml.replace(_SOURCE_LINE, _SOURCE_PATCH)
    # Pin the button image to the left of its (now wider) row so the negative
    # left margin actually moves it flush with the screen edge instead of
    # re-centring it.
    qml = qml.replace("Layout.alignment: Qt.AlignVCenter | Qt.AlignHCenter",
                      "Layout.alignment: Qt.AlignVCenter | Qt.AlignLeft")
    # The image is drawn shifted left by the overhang, so don't reserve that
    # width on the right of the applet as well.
    qml = qml.replace("        Layout.preferredWidth: sizing.preferredWidth\n",
                      f"        Layout.preferredWidth: sizing.preferredWidth - {overhang_left}\n", 1)
    qml = qml.replace(
        _ROW_ANCHOR,
        _ROW_ANCHOR
        + f"            anchors.topMargin: -{overhang_vertical}\n"
        + f"            anchors.bottomMargin: -{overhang_vertical}\n"
        + f"            anchors.leftMargin: -{overhang_left}\n",
    )
    if theme is not None and theme.parts("startpanel"):
        import startmenu_gen
        images = Path(staging) / "contents/images/start-menu"
        data = startmenu_gen.export(theme, images)
        # Relative URLs survive staging rename, moving the user profile, and
        # reinstalling from the AppImage; no build-machine paths in live QML.
        prefix = images.resolve().as_uri() + "/"
        def relative(value):
            if isinstance(value, dict):
                return {key: relative(item) for key, item in value.items()}
            if isinstance(value, list):
                return [relative(item) for item in value]
            if isinstance(value, str) and value.startswith(prefix):
                return "../images/start-menu/" + value[len(prefix):]
            return value
        ui = Path(staging) / "contents/ui"
        for filename in ("StartMenu.qml", "XpBackend.qml", "XpFullRepresentation.qml", "XpProgramsPopup.qml"):
            shutil.copy2(paths._shipped("start-menu", filename), ui / filename)
        (ui / "XpTheme.js").write_text(".pragma library\nvar data = " + json.dumps(relative(data)) + ";\n")
        old = "fullRepresentation: FullRepresentation { focus: true }"
        if qml.count(old) != 1:
            raise RuntimeError("Unexpected Kickoff full representation; not replacing the installed applet")
        qml = qml.replace(old, "fullRepresentation: XpFullRepresentation { launcher: kickoff; focus: true }")
        # Use KDE's actual app name, not a regex that might remove legitimate
        # parentheses from a name. Pinned descriptions have their own line.
        name_format = "appNameFormat: Plasmoid.configuration.appNameFormat"
        if qml.count(name_format) != 1:
            raise RuntimeError("Unexpected Kickoff name format; not replacing the installed applet")
        qml = qml.replace(name_format, "appNameFormat: 0 // NameOnly for the XP menu")
    with open(main_qml, "w", encoding="utf-8") as f:
        f.write(qml)

    if os.path.isdir(dest):
        shutil.rmtree(dest)
    os.rename(staging, dest)
    return _tree_hash(dest) != before
