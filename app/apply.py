"""Install and apply a generated Aurorae package + color scheme on the live
Plasma session via the standard CLI tools (kpackagetool6, kwriteconfig6,
plasma-apply-colorscheme, qdbus)."""
from __future__ import annotations

import os
import time

import hostexec as host

AURORAE_THEMES_DIR = os.path.expanduser("~/.local/share/aurorae/themes")
COLOR_SCHEMES_DIR = os.path.expanduser("~/.local/share/color-schemes")


def install_aurorae_theme(pkg_dir: str, plugin_id: str) -> None:
    dest = os.path.join(AURORAE_THEMES_DIR, plugin_id)
    os.makedirs(AURORAE_THEMES_DIR, exist_ok=True)
    if os.path.islink(dest) or os.path.exists(dest):
        if os.path.islink(dest) or os.path.isfile(dest):
            os.remove(dest)
        else:
            import shutil

            shutil.rmtree(dest)
    import shutil

    shutil.copytree(pkg_dir, dest)


def apply_aurorae_theme(plugin_id: str) -> None:
    import title_shadow
    title_shadow.install(AURORAE_THEMES_DIR)
    # Group is "org.kde.kdecoration2" per kwindecorationsettings.kcfg -- kept
    # for config-file compat even though the KWin C++ ABI moved to
    # KDecoration3. Both "library" (the decoration plugin/engine) and
    # "theme" (the specific Aurorae SVG theme id) must be set, or KWin keeps
    # using whatever plugin "library" already pointed at (Breeze, by default).
    theme_key = f"__aurorae__svg__{plugin_id}"

    def select(library: str, theme: str) -> None:
        for key, value in (("library", library), ("theme", theme)):
            host.run(
                ["kwriteconfig6", "--file", "kwinrc", "--group", "org.kde.kdecoration2",
                 "--key", key, value],
                check=True,
            )
        host.run([host.resolve("qdbus6", "qdbus"), "org.kde.KWin", "/KWin", "reconfigure"], check=False)

    # Aurorae shares one cached QML renderer across SVG themes. Its generated
    # shadow palette must reload even when switching to a DIFFERENT theme id;
    # otherwise Silver can retain the old blue shadow from that renderer.
    # Bounce through Breeze to release it (and refresh same-id SVGs as well).
    current = host.run(
        ["kreadconfig6", "--file", "kwinrc", "--group", "org.kde.kdecoration2", "--key", "theme"],
        capture=True,
    ).stdout.strip()
    if current.startswith("__aurorae__svg__"):
        select("org.kde.breeze", "Breeze")
        time.sleep(0.5)
    select("org.kde.kwin.aurorae", theme_key)


def install_colorscheme(colors_text: str, name: str) -> str:
    os.makedirs(COLOR_SCHEMES_DIR, exist_ok=True)
    path = os.path.join(COLOR_SCHEMES_DIR, f"{name}.colors")
    with open(path, "w", encoding="utf-8") as f:
        # KConfig ignores comment lines; this is how revert.py tells our
        # generated schemes apart from ones the user made themselves.
        f.write("# generated by XPLasma\n")
        f.write(colors_text)
    return path


def apply_colorscheme(name: str) -> None:
    host.run(["plasma-apply-colorscheme", name], check=True)


DESKTOP_THEMES_DIR = os.path.expanduser("~/.local/share/plasma/desktoptheme")


def install_desktoptheme(pkg_dir: str, plugin_id: str) -> None:
    import shutil

    dest = os.path.join(DESKTOP_THEMES_DIR, plugin_id)
    os.makedirs(DESKTOP_THEMES_DIR, exist_ok=True)
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    shutil.copytree(pkg_dir, dest)


def apply_desktoptheme(plugin_id: str) -> None:
    host.run(["plasma-apply-desktoptheme", plugin_id], check=True)
    # A running plasmashell neither discovers a theme package created after
    # it started nor reliably re-reads regenerated SVGs of the current one;
    # it keeps painting the (translucent) fallback. Restarting the shell
    # service is the only dependable way to get the new panel art on screen.
    host.run(["systemctl", "--user", "restart", "plasma-plasmashell.service"], check=False)
    time.sleep(5)


def _plasma_script(script: str) -> str:
    return host.run(
        [host.resolve("qdbus6", "qdbus"),
         "org.kde.plasmashell", "/PlasmaShell", "org.kde.PlasmaShell.evaluateScript", script],
        check=True, capture=True,
    ).stdout.strip()


def apply_panel_settings(height: int) -> str:
    """Anchor every bottom panel like an XP taskbar: not floating, opaque,
    full width, at the theme's taskbar height. Returns a summary of the
    previous values so they can be put back by hand."""
    script = (
        "var out = [];"
        "var ps = panels();"
        "for (var i = 0; i < ps.length; i++) {"
        "  var p = ps[i];"
        "  if (p.location !== 'bottom') continue;"
        "  out.push('panel ' + p.id + ': floating=' + p.floating + ' height=' + p.height + "
        "           ' opacity=' + p.opacity + ' alignment=' + p.alignment + ' lengthMode=' + p.lengthMode);"
        "  p.floating = false;"
        f"  p.height = {int(height)};"
        "  p.opacity = 'opaque';"
        "  p.alignment = 'left';"
        "  p.lengthMode = 'fill';"
        "}"
        "print(out.join('\\n'));"
    )
    return _plasma_script(script)


def apply_wallpaper_color(rgb: tuple[int, int, int]) -> None:
    """Solid desktop colour (Windows Classic default) via the org.kde.color plugin."""
    color = _hex_color(rgb)
    script = (
        "var ds = desktops();"
        "for (var i = 0; i < ds.length; i++) {"
        "  var d = ds[i];"
        "  d.wallpaperPlugin = 'org.kde.color';"
        '  d.currentConfigGroup = ["Wallpaper", "org.kde.color", "General"];'
        f'  d.writeConfig("Color", "{color}");'
        "}"
    )
    host.run(
        [host.resolve("qdbus6", "qdbus"),
         "org.kde.plasmashell", "/PlasmaShell", "org.kde.PlasmaShell.evaluateScript", script],
        check=True,
    )


def _hex_color(rgb: tuple[int, int, int]) -> str:
    # "#rrggbb": Plasma treats a "0,0,0" triple as unset and paints white.
    return "#%02x%02x%02x" % tuple(rgb)


def apply_wallpaper(image_path: str, fill_mode: int | None = None,
                    color: tuple[int, int, int] | None = None) -> None:
    """Set the desktop image, and optionally how it sits on the background.

    `color` is the background *behind* the image -- the same value XP's
    Display Properties exposes as "Color:". It only shows where the image does
    not reach (Center and Tile leave a border; Stretch covers everything), but
    it is a real setting rather than a decoration, and it is the value
    theme_presets.current_desktop() reads back, so it has to be written here or
    a chosen colour is silently lost on the next Save As.
    """
    host.run(["plasma-apply-wallpaperimage", os.path.abspath(image_path)], check=True)
    if fill_mode is None and color is None:
        return  # keep whatever positioning and colour the user currently has
    # plasma-apply-wallpaperimage only sets the image; these two live beside it
    # in the image plugin's config, and go through the same scripting interface.
    writes = ""
    if fill_mode is not None:
        writes += f'  d.writeConfig("FillMode", {int(fill_mode)});'
    if color is not None:
        writes += f'  d.writeConfig("Color", "{_hex_color(color)}");'
    script = (
        "var ds = desktops();"
        "for (var i = 0; i < ds.length; i++) {"
        "  var d = ds[i];"
        "  if (d.wallpaperPlugin !== 'org.kde.image') continue;"
        '  d.currentConfigGroup = ["Wallpaper", "org.kde.image", "General"];'
        + writes +
        "}"
    )
    host.run(
        [host.resolve("qdbus6", "qdbus"),
         "org.kde.plasmashell", "/PlasmaShell", "org.kde.PlasmaShell.evaluateScript", script],
        check=True,
    )
