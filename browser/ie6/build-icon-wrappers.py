#!/usr/bin/env python3
"""Give high-resolution XP artwork a 16 CSS-pixel intrinsic size.

Embed the unchanged PNG so SVG image documents need no external resource loads.
Explicit Firefox/CSS dimensions (24px toolbars, 32px notices, etc.) still win.
"""
import argparse
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def wrappers():
    icons = ROOT / 'chrome/ie6-icons'
    for image in sorted(icons.glob('*.png')):
        # Application branding and the original animated flag have their own size.
        if image.stem == 'application-ie' or image.stem.startswith('windows'):
            continue
        data = base64.b64encode(image.read_bytes()).decode('ascii')
        yield icons / 'sized' / (image.stem + '.svg'), (
            '<!-- Generated by build-icon-wrappers.py; artwork/license unchanged. -->\n'
            '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
            'width="16" height="16" viewBox="0 0 16 16">\n'
            f'  <image width="16" height="16" xlink:href="data:image/png;base64,{data}"/>\n'
            '</svg>\n'
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed wrappers need regeneration')
    args = parser.parse_args()
    stale = []
    for path, content in wrappers():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Regenerate XP icon wrappers: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
